package face_recognition.service;

import face_recognition.dto.notification.*;
import face_recognition.dto.response.WarnedNotificationSendResponse;
import face_recognition.model.*;
import face_recognition.repository.*;
import face_recognition.specification.NotificationSpecification;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.PageRequest;
import org.springframework.data.domain.Pageable;
import org.springframework.security.core.Authentication;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.util.List;
import java.util.stream.Collectors;

@Slf4j
@Service
@RequiredArgsConstructor
public class NotificationAdminService {

    private final NotificationRepository notificationRepository;
    private final NotificationRecipientRepository recipientRepository;
    private final AutoNotificationConfigRepository configRepository;
    private final UserRepository userRepository;
    private final SubjectRepository subjectRepository;
    private final ClassRoomRepository classRoomRepository;
    private final AttendanceRecordRepository attendanceRecordRepository;
    private final NotificationMailService notificationMailService;
    private final ClassRoomService classRoomService; // dùng lại resolveTeacherId đã có



    private Subject requireLinkedStudent(Long userId) {
        if (userId == null) throw new IllegalArgumentException("Thiếu userId");
        return subjectRepository.findByLinkedUserId(userId)
                .orElseThrow(() -> {
                    log.warn("Không tìm thấy sinh viên liên kết với userId={} (chưa liên kết tài khoản hoặc đã bị xóa)", userId);
                    return new IllegalArgumentException("Sinh viên chưa liên kết tài khoản nên không thể nhận thông báo");
                });
    }


    // ===== Gửi thông báo + email cảnh báo cho toàn bộ SV bị cảnh báo (ADMIN only) =====
    @Transactional
    public WarnedNotificationSendResponse sendWarningToWarnedStudents(String createdBy) {
        AutoNotificationConfig cfg = getOrCreateConfig();
        List<WarnedStudentResponse> warned = getWarnedSubjectsWithCount(cfg.getWarningThreshold());

        int notificationsSent = 0;
        int emailsSent = 0;
        int emailsSkipped = 0;

        for (WarnedStudentResponse w : warned) {
            if (w.getUserId() == null) continue;
            User user = userRepository.findById(w.getUserId()).orElse(null);
            if (user == null) continue;

            String content = renderTemplate(cfg.getMessageTemplate(), w);

            Notification notification = Notification.builder()
                    .title("Cảnh báo nghỉ học")
                    .content(content)
                    .type(NotificationType.WARNING)
                    .target(NotificationTarget.SINGLE_USER)
                    .createdBy(createdBy)
                    .isAutoGenerated(true)
                    .isActive(true)
                    .isDeleted(false)
                    .build();
            notification = notificationRepository.save(notification);
            attachRecipients(notification, List.of(user));
            notificationsSent++;

            Subject subject = subjectRepository.findById(w.getSubjectId()).orElse(null);
            String email = subject != null ? subject.getEmail() : null;

            if (isValidEmail(email)) {
                notificationMailService.sendWarningEmailAsync(email, w.getFullName(), content);
                emailsSent++;
            } else {
                emailsSkipped++;
                log.info("Bỏ qua gửi email cho SV {} vì email rỗng/không hợp lệ", w.getStudentCode());
            }
        }

        return WarnedNotificationSendResponse.builder()
                .totalStudents(warned.size())
                .notificationsSent(notificationsSent)
                .emailsSent(emailsSent)
                .emailsSkipped(emailsSkipped)
                .build();
    }

    private String renderTemplate(String template, WarnedStudentResponse w) {
        String t = (template == null || template.isBlank())
                ? "Bạn đã nghỉ học {absentCount} buổi. Vui lòng liên hệ giáo viên để được hỗ trợ."
                : template;
        return t.replace("{fullName}", nullToEmpty(w.getFullName()))
                .replace("{absentCount}", String.valueOf(w.getAbsentCount()))
                .replace("{subjectName}", nullToEmpty(w.getClassName()));
    }

    private String nullToEmpty(String s) {
        return s == null ? "" : s;
    }

    private boolean isValidEmail(String email) {
        return email != null && !email.isBlank()
                && email.matches("^[A-Za-z0-9+_.-]+@(.+)$");
    }

    // ===== Cập nhật trạng thái hoạt động của thông báo =====
    @Transactional
    public NotificationAdminResponse updateStatus(Long id, Boolean isActive, Authentication authentication) {
        if (isActive == null) {
            throw new IllegalArgumentException("Thiếu trạng thái isActive");
        }
        Notification notification = notificationRepository.findById(id)
                .orElseThrow(() -> new IllegalArgumentException("Thông báo không tồn tại"));

        validateTeacherOwnsNotification(notification, authentication);

        notification.setIsActive(isActive);
        notification = notificationRepository.save(notification);

        return NotificationAdminResponse.from(notification);
    }

    // ===== Danh sách thông báo =====
    public Page<NotificationAdminResponse> getNotifications(String search, String status, int page, int size,
                                                            Authentication authentication) {
        Pageable pageable = PageRequest.of(page, size,
                org.springframework.data.domain.Sort.by("createdAt").descending());

        Long teacherId = classRoomService.resolveTeacherId(authentication);
        if (teacherId != null) {
            String teacherUsername = authentication.getName();
            return notificationRepository
                    .findAll(NotificationSpecification.withFiltersForTeacher(search, status, teacherUsername, teacherId), pageable)
                    .map(NotificationAdminResponse::from);
        }

        return notificationRepository
                .findAll(NotificationSpecification.withFilters(search, status), pageable)
                .map(NotificationAdminResponse::from);
    }

    // ===== Tạo + gửi thông báo =====
    @Transactional
    public NotificationAdminResponse createAndSend(CreateNotificationRequest req, String createdBy, Authentication authentication) {
        Long teacherId = classRoomService.resolveTeacherId(authentication);

        if (teacherId != null) {
            validateTeacherTarget(req, teacherId);
        }

        Notification notification = Notification.builder()
                .title(req.getTitle())
                .content(req.getContent())
                .type(req.getType() != null ? req.getType() : NotificationType.INFO)
                .target(req.getTarget())
                .createdBy(createdBy)
                .isAutoGenerated(false)
                .isActive(true)
                .isDeleted(false)
                .build();

        if (req.getTarget() == NotificationTarget.CLASS && req.getClassRoomId() != null) {
            ClassRoom cr = classRoomRepository.findById(req.getClassRoomId())
                    .orElseThrow(() -> new IllegalArgumentException("Lớp không tồn tại"));
            notification.setClassRoom(cr);
        }

        List<User> recipients = resolveRecipients(req);

        if (recipients.isEmpty()) {
            log.warn("Không tìm thấy người nhận cho target: {}, thông báo vẫn được lưu nhưng không có ai nhận",
                    req.getTarget());
        }

        notification = notificationRepository.save(notification);

        if (!recipients.isEmpty()) {
            attachRecipients(notification, recipients);
        }

        return NotificationAdminResponse.from(notification);
    }

    // Nếu người gửi là TEACHER: chỉ được chọn target CLASS (lớp mình phụ trách) hoặc SINGLE_USER (sinh viên lớp mình)
    private void validateTeacherTarget(CreateNotificationRequest req, Long teacherId) {
        switch (req.getTarget()) {
            case CLASS -> {
                if (req.getClassRoomId() == null) throw new IllegalArgumentException("Thiếu classRoomId");
                ClassRoom cr = classRoomRepository.findById(req.getClassRoomId())
                        .orElseThrow(() -> new IllegalArgumentException("Lớp không tồn tại"));
                boolean owns = cr.getTeacher() != null && cr.getTeacher().getId().equals(teacherId);
                if (!owns) throw new IllegalArgumentException("Bạn không có quyền gửi thông báo cho lớp này!");
            }
            case SINGLE_USER -> {
                Subject subject = requireLinkedStudent(req.getUserId());
                boolean owns = subject.getClassRoom() != null
                        && subject.getClassRoom().getTeacher() != null
                        && subject.getClassRoom().getTeacher().getId().equals(teacherId);
                if (!owns) throw new IllegalArgumentException("Bạn không có quyền gửi thông báo cho sinh viên này!");
            }
            default -> throw new IllegalArgumentException("Bạn không có quyền gửi thông báo với đối tượng này!");
        }
    }

    private List<User> resolveRecipients(CreateNotificationRequest req) {
        return switch (req.getTarget()) {
            case SINGLE_USER -> {
                requireLinkedStudent(req.getUserId());
                yield List.of(userRepository.findById(req.getUserId())
                        .orElseThrow(() -> new IllegalArgumentException("Người dùng không tồn tại")));
            }
            case TEACHER -> {
                if (req.getUserId() == null) throw new IllegalArgumentException("Thiếu userId");
                User teacher = userRepository.findById(req.getUserId())
                        .orElseThrow(() -> new IllegalArgumentException("Giáo viên không tồn tại"));
                if (teacher.getRole() != User.Role.TEACHER)
                    throw new IllegalArgumentException("Tài khoản được chọn không phải giáo viên!");
                yield List.of(teacher);
            }
            case CLASS -> {
                if (req.getClassRoomId() == null) throw new IllegalArgumentException("Thiếu classRoomId");
                yield subjectRepository.findByClassRoomId(req.getClassRoomId()).stream()
                        .map(Subject::getLinkedUser)
                        .filter(java.util.Objects::nonNull)
                        .collect(Collectors.toList());
            }
            case WARNED_STUDENTS -> {
                AutoNotificationConfig cfg = getOrCreateConfig();
                yield getWarnedSubjects(cfg.getWarningThreshold()).stream()
                        .map(Subject::getLinkedUser)
                        .filter(java.util.Objects::nonNull)
                        .collect(Collectors.toList());
            }
            case ADMINS -> userRepository.findByRole(User.Role.ADMIN);
            case ALL -> userRepository.findAll();
        };
    }

    private void attachRecipients(Notification notification, List<User> users) {
        List<NotificationRecipient> recs = users.stream()
                .distinct()
                .map(u -> NotificationRecipient.builder()
                        .notification(notification)
                        .user(u)
                        .isRead(false)
                        .isHidden(false)
                        .build())
                .collect(Collectors.toList());
        recipientRepository.saveAll(recs);
        notification.setRecipients(recs);
    }

    // ===== Xóa thông báo (xóa mềm) =====
    @Transactional
    public void deleteNotification(Long id, Authentication authentication) {
        Notification notification = notificationRepository.findById(id)
                .orElseThrow(() -> new IllegalArgumentException("Thông báo không tồn tại"));

        validateTeacherOwnsNotification(notification, authentication);

        notification.setIsDeleted(true);
        notificationRepository.save(notification);
    }

    // Teacher chỉ được sửa trạng thái / xóa thông báo do chính mình tạo
    private void validateTeacherOwnsNotification(Notification notification, Authentication authentication) {
        Long teacherId = classRoomService.resolveTeacherId(authentication);
        if (teacherId == null) return; // ADMIN không giới hạn

        String teacherUsername = authentication.getName();
        if (!teacherUsername.equals(notification.getCreatedBy())) {
            throw new IllegalArgumentException("Bạn chỉ có thể thao tác với thông báo do chính mình tạo!");
        }
    }

    // ===== Sinh viên bị cảnh báo (ADMIN only) =====
    public List<WarnedStudentResponse> getWarnedStudents() {
        AutoNotificationConfig cfg = getOrCreateConfig();
        return getWarnedSubjectsWithCount(cfg.getWarningThreshold());
    }

    private List<Subject> getWarnedSubjects(int threshold) {
        return getWarnedSubjectsWithCount(threshold).stream()
                .map(w -> subjectRepository.findById(w.getSubjectId()).orElse(null))
                .filter(java.util.Objects::nonNull)
                .collect(Collectors.toList());
    }

    private List<WarnedStudentResponse> getWarnedSubjectsWithCount(int threshold) {
        List<Object[]> rows = attendanceRecordRepository.findSubjectIdsWithAbsencesAtLeast(threshold, null);
        return rows.stream().map(row -> {
            Long subjectId = (Long) row[0];
            long count = (Long) row[1];
            Subject s = subjectRepository.findById(subjectId).orElse(null);
            if (s == null) return null;
            return WarnedStudentResponse.builder()
                    .subjectId(s.getId())
                    .userId(s.getLinkedUser() != null ? s.getLinkedUser().getId() : null)
                    .studentCode(s.getStudentCode())
                    .fullName(s.getFullName())
                    .className(s.getClassRoom() != null ? s.getClassRoom().getName() : null)
                    .absentCount(count)
                    .build();
        }).filter(java.util.Objects::nonNull).collect(Collectors.toList());
    }

    // ===== Cấu hình tự động gửi (ADMIN only) =====
    public AutoNotificationConfig getOrCreateConfig() {
        return configRepository.findAll().stream().findFirst()
                .orElseGet(() -> configRepository.save(AutoNotificationConfig.builder()
                        .warningThreshold(3)
                        .autoSendThreshold(2)
                        .enabled(true)
                        .messageTemplate("Bạn đã nghỉ học {absentCount} buổi môn {subjectName}. Vui lòng liên hệ giáo viên để được hỗ trợ.")
                        .build()));
    }

    @Transactional
    public AutoNotificationConfig updateConfig(AutoNotificationConfigRequest req) {
        AutoNotificationConfig cfg = getOrCreateConfig();
        if (req.getWarningThreshold() != null) cfg.setWarningThreshold(req.getWarningThreshold());
        if (req.getAutoSendThreshold() != null) cfg.setAutoSendThreshold(req.getAutoSendThreshold());
        if (req.getEnabled() != null) cfg.setEnabled(req.getEnabled());
        if (req.getMessageTemplate() != null) cfg.setMessageTemplate(req.getMessageTemplate());
        return configRepository.save(cfg);
    }
}