package face_recognition.service;

import face_recognition.model.*;
import face_recognition.repository.*;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.scheduling.annotation.Scheduled;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.time.LocalDate;
import java.time.LocalDateTime;
import java.util.List;

@Slf4j
@Service
@RequiredArgsConstructor
public class AutoNotificationService {

    private final NotificationRepository notificationRepository;
    private final NotificationRecipientRepository recipientRepository;
    private final AutoNotificationConfigRepository configRepository;
    private final SubjectRepository subjectRepository;
    private final AttendanceRecordRepository attendanceRecordRepository;

    // Chạy mỗi ngày 6:00 sáng — có thể đổi cron tùy ý
    @Scheduled(cron = "0 0 6 * * *")
    @Transactional
    public void runAutoWarning() {
        AutoNotificationConfig cfg = configRepository.findAll().stream().findFirst().orElse(null);
        if (cfg == null || !Boolean.TRUE.equals(cfg.getEnabled())) {
            log.info("Auto-notification disabled, skip");
            return;
        }

        int threshold = cfg.getAutoSendThreshold();
        List<Object[]> rows = attendanceRecordRepository.findSubjectIdsWithAbsencesAtLeast(threshold, null);

        for (Object[] row : rows) {
            Long subjectId = (Long) row[0];
            long absentCount = (Long) row[1];

            Subject subject = subjectRepository.findById(subjectId).orElse(null);
            if (subject == null || subject.getLinkedUser() == null) continue;

            // tránh gửi trùng trong cùng ngày: kiểm tra đã có notification auto cho user này hôm nay chưa
            boolean alreadySentToday = recipientRepository.findByUserId(subject.getLinkedUser().getId())
                    .stream()
                    .anyMatch(r -> Boolean.TRUE.equals(r.getNotification().getIsAutoGenerated())
                            && r.getNotification().getCreatedAt().toLocalDate().equals(LocalDate.now()));
            if (alreadySentToday) continue;

            String content = cfg.getMessageTemplate()
                    .replace("{fullName}", subject.getFullName())
                    .replace("{subjectName}", subject.getClassRoom() != null ? subject.getClassRoom().getName() : "")
                    .replace("{absentCount}", String.valueOf(absentCount));

            Notification notification = Notification.builder()
                    .title("Cảnh báo nghỉ học")
                    .content(content)
                    .type(NotificationType.WARNING)
                    .target(NotificationTarget.SINGLE_USER)
                    .isAutoGenerated(true)
                    .isActive(true)
                    .createdBy("SYSTEM")
                    .build();
            notification = notificationRepository.save(notification);

            NotificationRecipient recipient = NotificationRecipient.builder()
                    .notification(notification)
                    .user(subject.getLinkedUser())
                    .isRead(false)
                    .isHidden(false)
                    .build();
            recipientRepository.save(recipient);

            log.info("Auto warning sent to user {} ({} buổi nghỉ)", subject.getLinkedUser().getId(), absentCount);
        }
    }
}